// Used for consistent error identification across the API
export const ERROR_CODES = {
  // Validation errors (400)
  VALIDATION_ERROR: 'VALIDATION_ERROR',
  INVALID_INPUT: 'INVALID_INPUT',
  INVALID_FORMAT: 'INVALID_FORMAT',
  MISSING_FIELD: 'MISSING_FIELD',

  // Authentication errors (401)
  UNAUTHORIZED: 'UNAUTHORIZED',
  INVALID_TOKEN: 'INVALID_TOKEN',
  TOKEN_EXPIRED: 'TOKEN_EXPIRED',
  INVALID_CREDENTIALS: 'INVALID_CREDENTIALS',

  // Authorization errors (403)
  FORBIDDEN: 'FORBIDDEN',
  INSUFFICIENT_PERMISSIONS: 'INSUFFICIENT_PERMISSIONS',
  NOT_MERCHANT_MEMBER: 'NOT_MERCHANT_MEMBER',

  // Not found errors (404)
  NOT_FOUND: 'NOT_FOUND',
  USER_NOT_FOUND: 'USER_NOT_FOUND',
  MERCHANT_NOT_FOUND: 'MERCHANT_NOT_FOUND',
  SUPPLIER_NOT_FOUND: 'SUPPLIER_NOT_FOUND',
  INGREDIENT_NOT_FOUND: 'INGREDIENT_NOT_FOUND',
  PURCHASE_ORDER_NOT_FOUND: 'PURCHASE_ORDER_NOT_FOUND',
  CATEGORY_NOT_FOUND: 'CATEGORY_NOT_FOUND',

  // Conflict errors (409)
  CONFLICT: 'CONFLICT',
  DUPLICATE_EMAIL: 'DUPLICATE_EMAIL',
  DUPLICATE_NAME: 'DUPLICATE_NAME',
  ALREADY_EXISTS: 'ALREADY_EXISTS',
  EMAIL_ALREADY_EXISTS: 'EMAIL_ALREADY_EXISTS',

  // Business logic errors (422)
  BUSINESS_RULE_VIOLATION: 'BUSINESS_RULE_VIOLATION',
  INVALID_STATUS_TRANSITION: 'INVALID_STATUS_TRANSITION',
  INSUFFICIENT_STOCK: 'INSUFFICIENT_STOCK',
  INVALID_AMOUNT: 'INVALID_AMOUNT',
  CANNOT_DELETE: 'CANNOT_DELETE',

  // Rate limiting (429)
  RATE_LIMIT_EXCEEDED: 'RATE_LIMIT_EXCEEDED',

  // Server errors (500)
  INTERNAL_ERROR: 'INTERNAL_ERROR',
  DATABASE_ERROR: 'DATABASE_ERROR',
  SERVICE_UNAVAILABLE: 'SERVICE_UNAVAILABLE',
} as const;

// Type for error codes
export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

// HTTP status codes mapping
export const ERROR_HTTP_STATUS: Record<ErrorCode, ContentfulStatusCode> = {
  [ERROR_CODES.VALIDATION_ERROR]: 400,
  [ERROR_CODES.INVALID_INPUT]: 400,
  [ERROR_CODES.INVALID_FORMAT]: 400,
  [ERROR_CODES.MISSING_FIELD]: 400,

  [ERROR_CODES.UNAUTHORIZED]: 401,
  [ERROR_CODES.INVALID_TOKEN]: 401,
  [ERROR_CODES.TOKEN_EXPIRED]: 401,
  [ERROR_CODES.INVALID_CREDENTIALS]: 401,

  [ERROR_CODES.FORBIDDEN]: 403,
  [ERROR_CODES.INSUFFICIENT_PERMISSIONS]: 403,
  [ERROR_CODES.NOT_MERCHANT_MEMBER]: 403,

  [ERROR_CODES.NOT_FOUND]: 404,
  [ERROR_CODES.USER_NOT_FOUND]: 404,
  [ERROR_CODES.MERCHANT_NOT_FOUND]: 404,
  [ERROR_CODES.SUPPLIER_NOT_FOUND]: 404,
  [ERROR_CODES.INGREDIENT_NOT_FOUND]: 404,
  [ERROR_CODES.PURCHASE_ORDER_NOT_FOUND]: 404,
  [ERROR_CODES.CATEGORY_NOT_FOUND]: 404,

  [ERROR_CODES.CONFLICT]: 409,
  [ERROR_CODES.DUPLICATE_EMAIL]: 409,
  [ERROR_CODES.DUPLICATE_NAME]: 409,
  [ERROR_CODES.ALREADY_EXISTS]: 409,
  [ERROR_CODES.EMAIL_ALREADY_EXISTS]: 409,

  [ERROR_CODES.BUSINESS_RULE_VIOLATION]: 422,
  [ERROR_CODES.INVALID_STATUS_TRANSITION]: 422,
  [ERROR_CODES.INSUFFICIENT_STOCK]: 422,
  [ERROR_CODES.INVALID_AMOUNT]: 422,
  [ERROR_CODES.CANNOT_DELETE]: 422,

  [ERROR_CODES.RATE_LIMIT_EXCEEDED]: 429,

  [ERROR_CODES.INTERNAL_ERROR]: 500,
  [ERROR_CODES.DATABASE_ERROR]: 500,
  [ERROR_CODES.SERVICE_UNAVAILABLE]: 503,
};

// Get HTTP status code for an error code
export const getHttpStatusForError = (code: ErrorCode): ContentfulStatusCode => {
  return ERROR_HTTP_STATUS[code] || 500;
};
