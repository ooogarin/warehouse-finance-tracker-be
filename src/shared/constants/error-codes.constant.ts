import type { ContentfulStatusCode } from 'hono/utils/http-status';

// App error code catalog (keep this intentionally small)
export const APP_ERROR_CODES = {
  VALIDATION_ERROR: 'VALIDATION_ERROR',
  UNAUTHORIZED: 'UNAUTHORIZED',
  INVALID_TOKEN: 'INVALID_TOKEN',
  TOKEN_EXPIRED: 'TOKEN_EXPIRED',
  FORBIDDEN: 'FORBIDDEN',
  NOT_FOUND: 'NOT_FOUND',
  CONFLICT: 'CONFLICT',
  DUPLICATE_EMAIL: 'DUPLICATE_EMAIL',
  BUSINESS_RULE_VIOLATION: 'BUSINESS_RULE_VIOLATION',
  INTERNAL_ERROR: 'INTERNAL_ERROR',
  DATABASE_ERROR: 'DATABASE_ERROR',
} as const;

export type AppErrorCode = (typeof APP_ERROR_CODES)[keyof typeof APP_ERROR_CODES];

export const APP_ERROR_STATUS_BY_CODE: Record<AppErrorCode, ContentfulStatusCode> = {
  [APP_ERROR_CODES.VALIDATION_ERROR]: 400,
  [APP_ERROR_CODES.UNAUTHORIZED]: 401,
  [APP_ERROR_CODES.INVALID_TOKEN]: 401,
  [APP_ERROR_CODES.TOKEN_EXPIRED]: 401,
  [APP_ERROR_CODES.FORBIDDEN]: 403,
  [APP_ERROR_CODES.NOT_FOUND]: 404,
  [APP_ERROR_CODES.CONFLICT]: 409,
  [APP_ERROR_CODES.DUPLICATE_EMAIL]: 409,
  [APP_ERROR_CODES.BUSINESS_RULE_VIOLATION]: 422,
  [APP_ERROR_CODES.INTERNAL_ERROR]: 500,
  [APP_ERROR_CODES.DATABASE_ERROR]: 500,
};

export const getStatusCodeForAppError = (code: AppErrorCode): ContentfulStatusCode => {
  return APP_ERROR_STATUS_BY_CODE[code] || 500;
};
